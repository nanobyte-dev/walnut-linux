def secret_uses(x):
	"""The uses of the secrets context in the `${{ }}` expressions of x: names (secrets.NAME), and "<dynamic>" for
	any other form (toJSON(secrets), secrets['X'], secrets[format(...)], a bare secrets)."""
	import yaml
	out = []
	for expr in re.findall(r"\$\{\{(.*?)\}\}", yaml.dump(x, width=10**9), re.S):
		out += re.findall(r"\bsecrets\.(\w+)", expr)
		if re.search(r"\bsecrets\b(?!\.\w)", expr):
			out.append("<dynamic>")
	return out


def secret_rules(name, doc):
	"""Secrets go to steps, and never to a job that runs code of the packages: no use of the secrets context at
	all (any form) in build-external, the release image's build and layer jobs; in any job a step that runs
	package code may name only the shared ccache's login; no secret in an env block of the workflow or of a job;
	a job passing secrets on (uses + secrets) only where it calls walnut-package.yml."""
	errs = []
	ref = secret_uses
	if ref(doc.get("env")):
		errs.append(f"{name}: a secret in the workflow-level env")
	for jname, job in (doc.get("jobs") or {}).items():
		if not isinstance(job, dict):
			continue
		if ref(job.get("env")):
			errs.append(f"{name}: job {jname}: a secret in the job-level env (steps only)")
		if "secrets" in job and job.get("uses") != "./.github/workflows/walnut-package.yml":
			errs.append(f"{name}: job {jname}: passes secrets to something other than walnut-package.yml")
		if (name, jname) in NO_SECRET_JOBS and (ref(job) or "secrets" in job):
			errs.append(f"{name}: job {jname} runs package code and references a secret")
		for st in job.get("steps") or []:
			if isinstance(st, dict) and PACKAGE_CODE_RE.search(str(st.get("run", ""))):
				bad = set(ref(st)) - {"WALNUT_CCACHE_AUTH"}
				if bad:
					errs.append(f"{name}: job {jname}: a step that runs package code references {sorted(bad)}")
	return errs


DEPLOY_KEY_ENVS = {"walnut-site.yml": {"walnut-site"}, "walnut-publish.yml": {"walnut-testing"},
                   "walnut-package.yml": {"walnut-stable"}, "release-image.yml": {"walnut-${{ inputs.channel }}"}}


def deploy_key_rules(name, doc):
	"""WALNUT_DEPLOY_KEY is an environment secret, one key per environment (V1): a job that names it has the
	environment this workflow is meant for, so a copied job cannot pick up another purpose's key."""
	errs = []
	if name not in DEPLOY_KEY_ENVS:	# a workflow outside the table: test_gen_workflows.py checks the real ones name the key nowhere else
		return errs
	for jname, job in (doc.get("jobs") or {}).items():
		if isinstance(job, dict) and "WALNUT_DEPLOY_KEY" in secret_uses(job):
			env = job.get("environment")
			env = env.get("name") if isinstance(env, dict) else env
			if env not in DEPLOY_KEY_ENVS.get(name, set()):
				errs.append(f"{name}: job {jname}: uses WALNUT_DEPLOY_KEY in environment {env!r} "
				            f"(want one of {sorted(DEPLOY_KEY_ENVS.get(name, set()))})")
	return errs


def pr_rules(name, doc):
	"""A workflow that runs on pull_request runs code from outside the repository's maintainers: it holds no secret,
	no environment, no write permission and calls nothing that passes secrets on."""
	on = doc.get("on", doc.get(True)) or {}
	if "pull_request" not in (on if isinstance(on, (dict, list, str)) else {}):
		return []
	errs = []
	if secret_uses(doc) or any("secrets" in j for j in (doc.get("jobs") or {}).values() if isinstance(j, dict)):
		errs.append(f"{name}: runs on pull_request and references a secret")
	for jname, job in (doc.get("jobs") or {}).items():
		if isinstance(job, dict) and "environment" in job:
			errs.append(f"{name}: job {jname}: runs on pull_request and uses an environment")
		if isinstance(job, dict) and "uses" in job:
			errs.append(f"{name}: job {jname}: runs on pull_request and calls another workflow")
	if not isinstance(doc.get("permissions"), (dict, str)):
		errs.append(f"{name}: runs on pull_request without a top-level permissions: key (the token would get the repository default)")
	perms = [doc.get("permissions")] + [j.get("permissions") for j in (doc.get("jobs") or {}).values() if isinstance(j, dict)]
	for pm in perms:
		if isinstance(pm, str) and pm != "read-all" or isinstance(pm, dict) and any(v not in ("read", "none") for v in pm.values()):
			errs.append(f"{name}: runs on pull_request with a permission above read")
	return errs


STABLE_ENVS = ("walnut-stable", "walnut-${{ inputs.channel }}")


def stable_rules(name, doc):
	"""Every job that can publish to stable (environment walnut-stable) needs the stable-gate job (environment
	walnut-stable-review: reviewers, no secret) unless the dispatcher is on the allowlist, and the condition is
	spelled out in the job's own `if:` and in its first step, so a skipped gate is never a bypass."""
	errs = []
	jobs = doc.get("jobs") or {}
	for jname, job in jobs.items():
		if not isinstance(job, dict):
			continue
		if job.get("environment") == "walnut-stable-review":
			if secret_uses(job) or "uses" in job or "secrets" in job:
				errs.append(f"{name}: job {jname}: the review environment's job references secrets or calls something")
			if jname != "stable-gate" or f"!{ALLOWED}" not in str(job.get("if")):
				errs.append(f"{name}: job {jname}: the review gate runs only for someone not on the allowlist")
		if job.get("environment") not in STABLE_ENVS:
			continue
		gate = jobs.get("stable-gate")
		needs = job.get("needs") if isinstance(job.get("needs"), list) else [job.get("needs")]
		cond = str(job.get("if"))
		first = (job.get("steps") or [{}])[0]
		if not isinstance(gate, dict) or gate.get("environment") != "walnut-stable-review" or f"!{ALLOWED}" not in str(gate.get("if")):
			errs.append(f"{name}: job {jname} publishes to stable but there is no stable-gate (environment walnut-stable-review, if: !allowlist)")
		gcond = str(gate.get("if")) if isinstance(gate, dict) else ""
		gneeds = gate.get("needs") if isinstance(gate, dict) else None
		gneeds = gneeds if isinstance(gneeds, list) else [gneeds]
		if "always()" not in gcond or any(f"needs.{n}.result == 'success'" not in gcond for n in gneeds if n):
			errs.append(f"{name}: stable-gate's `if` needs always() and the result of each job it needs (success() is false after a skipped ancestor, and the gate would be skipped with the run green)")
		out = jobs.get("stable-outcome")
		if not isinstance(out, dict) or "always()" not in str(out.get("if")) or jname not in (out.get("needs") or []) \
		        or "exit 1" not in str(out.get("steps")) or f"needs.{jname}.result != 'success'" not in str(out.get("if")):
			errs.append(f"{name}: no stable-outcome job that fails when job {jname} didn't complete a wanted stable publish")
		if "stable-gate" not in needs:
			errs.append(f"{name}: job {jname} publishes to stable without needing stable-gate")
		if ALLOWED not in cond or "needs.stable-gate.result == 'success'" not in cond or \
		        "needs.stable-gate.result == 'skipped'" not in cond:
			errs.append(f"{name}: job {jname}: its `if` must accept the gate's success, or a skipped gate plus the allowlist")
		env = first.get("env") or {}
		run = str(first.get("run"))
		if "needs.stable-gate.result" not in str(env.get("GATE")) or "vars.WALNUT_STABLE_PUBLISHERS" not in str(env.get("PUBLISHERS")) \
		        or "github.triggering_actor" not in str(env.get("ACTOR")) or '"$GATE" = skipped' not in run \
		        or "jq -e --arg a \"$ACTOR\"" not in run or ". == $a" not in run or 'type == "array"' not in run or "exit 1" not in run:
			errs.append(f"{name}: job {jname}: its first step must check the gate and the allowlist again")
	return errs


def workflow_lint(check_yaml=True):
	"""Rules over every file in .github/workflows/ (generated or not)."""
	errs = []
	for f in WORKFLOW_FILES():
		name = os.path.basename(f)
		if check_yaml:
			e = yaml_errors(name, open(f).read())
			errs += e
			if not e:
				import yaml
				doc = yaml.safe_load(open(f))
				errs += secret_rules(name, doc) + stable_rules(name, doc) + pr_rules(name, doc) + deploy_key_rules(name, doc)
		text = "\n".join(l for l in open(f).read().splitlines() if not l.lstrip().startswith("#")) + "\n"	# not comments
		if "pull_request_target" in text:
			errs.append(f"{name}: pull_request_target")
		for m in re.finditer(r"- uses: actions/checkout@\S+\n((?:        .*\n)*)", text):
			body = m.group(1)
			pc = re.search(r"persist-credentials: (.*)", body)
			ok = pc and (pc.group(1).split("#")[0].strip() in ("false", "${{ inputs.package == 'walnut-games' }}")
			             or (pc.group(1).split("#")[0].strip() == "true" and name == "walnut-site.yml"))
			if not ok:
				errs.append(f"{name}: a checkout without persist-credentials: false (true only where git lfs pull needs it)")
		if name not in WRITE_OK and re.search(r"^\s+[a-z-]+: write\s*$", text, re.M):
			errs.append(f"{name}: a write permission (only {sorted(WRITE_OK)} may hold one)")
		for st in re.split(r"\n      - ", text):
			if re.search(r"uses: actions/cache(?:/restore|/save)?@", st):
				if not re.search(r"if: .*steps\.(?:keys|key)\.outputs\.\w+ != ''", st) or "restore-keys" in st \
				        or not re.search(r"key: \$\{\{ steps\.(?:keys|key|base)\.outputs", st):
					errs.append(f"{name}: an Actions cache step that isn't guarded by, and keyed from, the salted key step")
		if STABLE_ENV_RE.search(text) and "refs/heads/main" not in text:
			errs.append(f"{name}: publishes to stable without a refs/heads/main check")
	return errs


def licensed_module():
	spec = importlib.util.spec_from_file_location("licensed", f"{ROOT}/tools/licensed.py")
	m = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(m)
	return m


def generate():
	"""{file name: text} of every workflow this generator owns"""
	lic = licensed_module()
	licensed = lic.names(ROOT)
	for d in subprocess.run([f"{ROOT}/tools/pkg-dir.sh", "--all"], stdout=subprocess.PIPE, text=True,
	                        check=True).stdout.split():
		DIRS[os.path.basename(d)] = d
	pkgs = sorted(p for p in DIRS if p not in licensed
	              and not any(re.match(g.replace("*", "[^/]+") + r"\Z", DIRS[p]) for g in lic.LICENSED_DIR_GLOBS))
	files = {}
	lists = lists_module().Lists(open(f"{ROOT}/github-ci/packages.toml").read())
	errs = tier_errors(pkgs, licensed, lists)
	if errs:
		raise SystemExit("\n".join(f"!! {e}" for e in errs))
	for pkg in pkgs:
		tier = lists.entries[pkg].tier

		paths = [f"{DIRS[pkg]}/**"] + [f"{v.rstrip('/')}/**" if os.path.isdir(f"{ROOT}/{v}") else v
		                         for v in conf(pkg, "VERSION_PATHS")]
		if conf(pkg, "BUILD") == ["xcc"]:
			paths = [f"github-ci/prebuilt/{pkg}.sha256"]
		text = f"""# Generated by github-ci/gen-workflows.py: don't edit, run it again.
name: "pkg: {pkg}"

on:
  push:
    branches: [main]
    paths:
{''.join(f'      - "{p}"' + chr(10) for p in paths)}  workflow_dispatch:
    inputs:
      target:
        description: "Build and publish to"
        type: choice
        options: [testing, stable]
        default: testing
      dry_run:
        description: "Stable only: build, then check the signing and upload keys without publishing"
        type: boolean
        default: false

concurrency:
  group: pkg-{pkg}-${{{{ inputs.target || 'testing' }}}}
  cancel-in-progress: true

jobs:
  package:
    uses: ./.github/workflows/walnut-package.yml
    with:
      package: {pkg}
      target: ${{{{ inputs.target || 'testing' }}}}
      tier: {tier}
      dry_run: ${{{{ inputs.dry_run || false }}}}
    secrets: inherit  # the stable signing keys are environment secrets: they reach the called jobs this way only
"""
		files[f"pkg-{pkg}.yml"] = text
	files["walnut-package.yml"] = package_workflow()
	files["walnut-publish.yml"] = PUBLISHER.replace("@WORKFLOWS@", "".join(f'      - "pkg: {p}"\n' for p in pkgs))
	return files


def main():
	files = generate()
	stale = [os.path.basename(f) for f in glob.glob(f"{WF}/pkg-*.yml") if os.path.basename(f) not in files]
	if "--check" in sys.argv[1:]:
		bad = [n for n, t in sorted(files.items())
		       if not os.path.exists(f"{WF}/{n}") or open(f"{WF}/{n}").read() != t] + stale
		for n in bad:
			print(f"!! .github/workflows/{n} isn't what github-ci/gen-workflows.py writes (run it)")
		print(f">> {len(files) - 2} package workflows, walnut-package.yml and walnut-publish.yml: {'%d stale' % len(bad) if bad else 'current'}")
		lint = workflow_lint()
		for e in lint:
			print(f"!! {e}")
		return 1 if bad or lint else 0
	for n, t in files.items():
		with open(f"{WF}/{n}", "w") as f:
			f.write(t)
	for n in stale:
		os.unlink(f"{WF}/{n}")
	print(f">> {len(files) - 2} package workflows, walnut-package.yml and walnut-publish.yml")
	return 0


if __name__ == "__main__":
	sys.exit(main())
