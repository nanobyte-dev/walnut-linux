#!/usr/bin/env python3
"""gen-workflows.py: writes .github/workflows/pkg-<name>.yml for every package GitHub builds
(every package tools/pkg-dir.sh --all lists except the licensed ones: tools/licensed.py names, and any
package in a licensed directory), and walnut-publish.yml, testing's one publisher, which starts when any
of them finishes. A push that changes the package's own files (its directory, and the sources
package.conf VERSION_PATHS says it carries) builds it for testing; the publisher puts it there. A
change to the shared build tools or a workflow builds nothing by itself (the owner, 2026-10-21: no
20 builds for a small change). "Run workflow" builds for the suite picked there, testing or stable;
stable is never built automatically and publishes from its own run, with the owner's approval.
ps3rsx also builds for testing after every linux build goes out (the publisher starts it: testing's
kernel needs its GPU module). Stale pkg-*.yml files are removed. Run it after adding or removing a
package; --check writes nothing and exits 1 when the files on disk aren't what it would write (make
test runs it). Packages: tools/pkg-dir.sh --all; licensed: tools/licensed.py. A VERSION_PATHS entry
is a GitHub path filter as it is (a directory gets /**): * stays within one path component and **
crosses them, as tools/deb-version.sh reads the same strings (git :(glob) pathspecs).
A BUILD=xcc package (package.conf: too big for a runner, built on the dev PC by tools/xcc-build.sh)
is not built here: its workflow starts on a change to github-ci/prebuilt/<name>.sha256 (written by
tools/prebuilt-upload.sh) and github-ci/build-package.sh takes the debs that file pins from the
GitHub release it names."""
import glob, importlib.util, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WF = f"{ROOT}/.github/workflows"
DIRS = {}	# package name -> its directory under packages/


PUBLISHER = """# Generated by github-ci/gen-workflows.py: don't edit, run it again.
# testing's one publisher (github-ci/batch-publish.py): every package build that finished
# successfully and isn't in testing yet goes out together, in one upload. It starts whenever a package
# workflow finishes, and every 10 minutes. One run at a time (a running publish is never cancelled);
# GitHub keeps one more waiting and cancels any older waiting one, which loses nothing: each run
# takes everything ready when it starts, and the waiting run starts after the running one.
#   check    what testing lacks (no secrets, no environment); "todo N"
#   publish  only when N > 0: downloads those artifacts, publishes them (github-ci/publish.sh, the
#            CI key, environment walnut-testing), then starts ps3rsx's build when linux went out
name: "walnut: publish testing"

on:
  workflow_run:
    workflows:
@WORKFLOWS@    types: [completed]
  schedule:
    - cron: "*/10 * * * *"
  workflow_dispatch:

concurrency:
  group: walnut-publish-testing
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  check:
    runs-on: ubuntu-24.04
    timeout-minutes: 15
    permissions:
      contents: read
      actions: read
    outputs:
      todo: ${{ steps.plan.outputs.todo }}
    steps:
      - uses: actions/checkout@v7
      - name: What testing lacks
        id: plan
        env:
          GITHUB_TOKEN: ${{ github.token }}
        run: |
          github-ci/batch-publish.py plan > "$RUNNER_TEMP/plan"
          cat "$RUNNER_TEMP/plan"
          echo "todo=$(sed -n 's/^todo //p' "$RUNNER_TEMP/plan")" >> "$GITHUB_OUTPUT"

  publish:
    needs: check
    if: needs.check.outputs.todo != '0'
    runs-on: ubuntu-24.04
    timeout-minutes: 300
    environment: walnut-testing
    permissions:
      contents: read
      actions: write  # artifacts, and starting ps3rsx's build after linux
    steps:
      - uses: actions/checkout@v7
      - name: Publish every build testing lacks
        env:
          GITHUB_TOKEN: ${{ github.token }}
          WALNUT_SIGN_KEY: ${{ secrets.WALNUT_TESTING_KEY }}
          WALNUT_DEPLOY_KEY_DATA: ${{ secrets.WALNUT_DEPLOY_KEY }}
        run: github-ci/batch-publish.py publish --work "$RUNNER_TEMP/publish"
"""


def conf(pkg, key):
	m = re.search(rf'^{key}="?([^"\n]*)"?$', open(f"{ROOT}/{DIRS[pkg]}/package.conf").read(), re.M)
	return m.group(1).split() if m else []


def licensed_module():
	spec = importlib.util.spec_from_file_location("licensed", f"{ROOT}/tools/licensed.py")
	m = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(m)
	return m


def generate():
	"""{file name: text} of every workflow this generator owns"""
	lic = licensed_module()
	licensed = lic.names(ROOT)
	for d in subprocess.run([f"{ROOT}/tools/pkg-dir.sh", "--all"], stdout=subprocess.PIPE, text=True,
	                        check=True).stdout.split():
		DIRS[os.path.basename(d)] = d
	pkgs = sorted(p for p in DIRS if p not in licensed
	              and not any(re.match(g.replace("*", "[^/]+") + r"\Z", DIRS[p]) for g in lic.LICENSED_DIR_GLOBS))
	files = {}
	for pkg in pkgs:
		paths = [f"{DIRS[pkg]}/**"] + [f"{v.rstrip('/')}/**" if os.path.isdir(f"{ROOT}/{v}") else v
		                         for v in conf(pkg, "VERSION_PATHS")]
		if conf(pkg, "BUILD") == ["xcc"]:
			paths = [f"github-ci/prebuilt/{pkg}.sha256"]
		text = f"""# Generated by github-ci/gen-workflows.py: don't edit, run it again.
name: "pkg: {pkg}"

on:
  push:
    branches: [main]
    paths:
{''.join(f'      - "{p}"' + chr(10) for p in paths)}  workflow_dispatch:
    inputs:
      target:
        description: "Build and publish to"
        type: choice
        options: [testing, stable]
        default: testing

concurrency:
  group: pkg-{pkg}-${{{{ inputs.target || 'testing' }}}}
  cancel-in-progress: true

jobs:
  package:
    uses: ./.github/workflows/walnut-package.yml
    with:
      package: {pkg}
      target: ${{{{ inputs.target || 'testing' }}}}
    secrets: inherit
"""
		files[f"pkg-{pkg}.yml"] = text
	files["walnut-publish.yml"] = PUBLISHER.replace("@WORKFLOWS@", "".join(f'      - "pkg: {p}"\n' for p in pkgs))
	return files


def main():
	files = generate()
	stale = [os.path.basename(f) for f in glob.glob(f"{WF}/pkg-*.yml") if os.path.basename(f) not in files]
	if "--check" in sys.argv[1:]:
		bad = [n for n, t in sorted(files.items())
		       if not os.path.exists(f"{WF}/{n}") or open(f"{WF}/{n}").read() != t] + stale
		for n in bad:
			print(f"!! .github/workflows/{n} isn't what github-ci/gen-workflows.py writes (run it)")
		print(f">> {len(files) - 1} package workflows and walnut-publish.yml: {'%d stale' % len(bad) if bad else 'current'}")
		return 1 if bad else 0
	for n, t in files.items():
		with open(f"{WF}/{n}", "w") as f:
			f.write(t)
	for n in stale:
		os.unlink(f"{WF}/{n}")
	print(f">> {len(files) - 1} package workflows and walnut-publish.yml")
	return 0


if __name__ == "__main__":
	sys.exit(main())
