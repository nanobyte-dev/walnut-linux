def conf(pkg, key):
	m = re.search(rf'^{key}="?([^"\n]*)"?$', open(f"{ROOT}/{DIRS[pkg]}/package.conf").read(), re.M)
	return m.group(1).split() if m else []


def lists_module():
	spec = importlib.util.spec_from_file_location("walnut_lists", f"{ROOT}/github-ci/walnut_lists.py")
	m = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(m)
	return m


FETCH_RE = re.compile(r"\b(curl|wget|git\s+clone|git\s+fetch|urlopen|urlretrieve|pip3?\s+install|npm\s+install|go\s+get|cargo\s+fetch)\b")
BUILD_FILE_RE = re.compile(r"(?:^|/)(?:rules|Makefile|[^/]*\.mk|[^/]*\.sh)\Z")
PREBUILT_OK = {"webkit2gtk"}	# BUILD=xcc: built on the dev PC, fetched by github-ci/build-package.sh against a sha256 pin


def tier_errors(pkgs, licensed, lists):
	"""Problems with packages.toml against the tree: a package without a tier or in another directory, a
	licensed entry that isn't, a package marked trusted whose source is an upstream tarball or whose build
	files fetch from the network (they would build with the shared ccache's login)."""
	errs = []
	for pkg in sorted(pkgs):
		e = lists.entries.get(pkg)
		if e is None:
			errs.append(f"{pkg}: no entry (so no tier) in github-ci/packages.toml")
			continue
		if e.dir != DIRS[pkg]:
			errs.append(f"{pkg}: packages.toml says {e.dir}, the package is in {DIRS[pkg]}")
		if e.tier == "licensed":
			errs.append(f"{pkg}: tier licensed, but it is not a licensed package")
		if e.tier != "trusted":
			continue
		if conf(pkg, "TYPE") == ["upstream"]:
			errs.append(f"{pkg}: trusted, but TYPE=upstream (an upstream tarball or repository is external)")
		if conf(pkg, "BUILD") == ["xcc"] and (pkg not in PREBUILT_OK or not os.path.exists(f"{ROOT}/github-ci/prebuilt/{pkg}.sha256")):
			errs.append(f"{pkg}: trusted, but BUILD=xcc fetches a prebuilt build and only {sorted(PREBUILT_OK)} with a sha256 pin may")
		for dp, dn, fns in os.walk(f"{ROOT}/{DIRS[pkg]}"):
			dn[:] = [d for d in dn if d not in ("patches", "files", ".git")]
			for fn in fns:
				rel = os.path.relpath(os.path.join(dp, fn), ROOT)
				if BUILD_FILE_RE.search(rel):
					for n, line in enumerate(open(f"{ROOT}/{rel}", errors="replace"), 1):
						if FETCH_RE.search(line.split("#")[0]):
							errs.append(f"{pkg}: trusted, but {rel}:{n} fetches from the network: {line.strip()[:80]}")
	for name in sorted(n for n in licensed if n in DIRS):
		e = lists.entries.get(name)
		if e is None or e.tier != "licensed":
			errs.append(f"{name}: licensed, but packages.toml has no such entry with tier licensed")
	return errs


WORKFLOW_FILES = lambda: sorted(glob.glob(f"{WF}/*.yml"))
STABLE_ENV_RE = re.compile(r"environment:\s*(?:walnut-stable|walnut-\$\{\{ inputs\.channel \}\})")


def yaml_errors(name, text):
	"""Whether the file is YAML GitHub will load: it parses (PyYAML, strictly: no duplicate key anywhere, which a
	second `jobs:` or a repeated step key would be) and has the top-level keys of a workflow."""
	try:
		import yaml
	except ImportError:
		return [f"{name}: python3-yaml is needed to check that the workflow is valid YAML"]

	class Strict(yaml.SafeLoader):
		pass

	def mapping(loader, node, deep=False):
		seen = set()
		for k, _ in node.value:
			key = loader.construct_object(k, deep=True)
			if key in seen:
				raise yaml.constructor.ConstructorError(None, None, f"duplicate key {key!r}", k.start_mark)
			seen.add(key)
		return yaml.SafeLoader.construct_mapping(loader, node, deep)
	Strict.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, mapping)
	try:
		doc = yaml.load(text, Strict)
	except yaml.YAMLError as e:
		return [f"{name}: not valid YAML: {str(e).splitlines()[0]} {str(e).splitlines()[-1] if len(str(e).splitlines()) > 1 else ''}".strip()]
	if not isinstance(doc, dict) or "jobs" not in doc or (True not in doc and "on" not in doc):
		return [f"{name}: no `on` and `jobs` at the top"]
	return []


def workflow_lint(check_yaml=True):
	"""Rules over every file in .github/workflows/ (generated or not)."""
	errs = []
	for f in WORKFLOW_FILES():
		name = os.path.basename(f)
		if check_yaml:
			errs += yaml_errors(name, open(f).read())
		text = "\n".join(l for l in open(f).read().splitlines() if not l.lstrip().startswith("#")) + "\n"	# not comments
		if re.search(r"^\s*secrets:\s*inherit\s*$", text, re.M):
			errs.append(f"{name}: secrets: inherit (pass each secret by name)")
		if "pull_request_target" in text:
			errs.append(f"{name}: pull_request_target")
		for m in re.finditer(r"- uses: actions/checkout@\S+\n((?:        .*\n)*)", text):
			body = m.group(1)
			pc = re.search(r"persist-credentials: (.*)", body)
			ok = pc and (pc.group(1).split("#")[0].strip() in ("false", "${{ inputs.package == 'walnut-games' }}")
			             or (pc.group(1).split("#")[0].strip() == "true" and name == "walnut-site.yml"))
			if not ok:
				errs.append(f"{name}: a checkout without persist-credentials: false (true only where git lfs pull needs it)")
		if STABLE_ENV_RE.search(text) and "refs/heads/main" not in text:
			errs.append(f"{name}: publishes to stable without a refs/heads/main check")
	return errs


def licensed_module():
	spec = importlib.util.spec_from_file_location("licensed", f"{ROOT}/tools/licensed.py")
	m = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(m)
	return m


def generate():
	"""{file name: text} of every workflow this generator owns"""
	lic = licensed_module()
	licensed = lic.names(ROOT)
	for d in subprocess.run([f"{ROOT}/tools/pkg-dir.sh", "--all"], stdout=subprocess.PIPE, text=True,
	                        check=True).stdout.split():
		DIRS[os.path.basename(d)] = d
	pkgs = sorted(p for p in DIRS if p not in licensed
	              and not any(re.match(g.replace("*", "[^/]+") + r"\Z", DIRS[p]) for g in lic.LICENSED_DIR_GLOBS))
	files = {}
	lists = lists_module().Lists(open(f"{ROOT}/github-ci/packages.toml").read())
	errs = tier_errors(pkgs, licensed, lists)
	if errs:
		raise SystemExit("\n".join(f"!! {e}" for e in errs))
	for pkg in pkgs:
		tier = lists.entries[pkg].tier
		secrets = "      WALNUT_DEPLOY_KEY: ${{ secrets.WALNUT_DEPLOY_KEY }}\n"
		if tier == "trusted":
			secrets += ("      WALNUT_CCACHE_AUTH: ${{ secrets.WALNUT_CCACHE_AUTH }}\n"
			            "      WALNUT_CACHE_SALT: ${{ secrets.WALNUT_CACHE_SALT }}\n")
		paths = [f"{DIRS[pkg]}/**"] + [f"{v.rstrip('/')}/**" if os.path.isdir(f"{ROOT}/{v}") else v
		                         for v in conf(pkg, "VERSION_PATHS")]
		if conf(pkg, "BUILD") == ["xcc"]:
			paths = [f"github-ci/prebuilt/{pkg}.sha256"]
		text = f"""# Generated by github-ci/gen-workflows.py: don't edit, run it again.
name: "pkg: {pkg}"

on:
  push:
    branches: [main]
    paths:
{''.join(f'      - "{p}"' + chr(10) for p in paths)}  workflow_dispatch:
    inputs:
      target:
        description: "Build and publish to"
        type: choice
        options: [testing, stable]
        default: testing
      dry_run:
        description: "Stable only: build, then check the signing and upload keys without publishing"
        type: boolean
        default: false

concurrency:
  group: pkg-{pkg}-${{{{ inputs.target || 'testing' }}}}
  cancel-in-progress: true

jobs:
  package:
    uses: ./.github/workflows/walnut-package.yml
    with:
      package: {pkg}
      target: ${{{{ inputs.target || 'testing' }}}}
      tier: {tier}
      dry_run: ${{{{ inputs.dry_run || false }}}}
    secrets:
{secrets}"""
		files[f"pkg-{pkg}.yml"] = text
	files["walnut-package.yml"] = package_workflow()
	files["walnut-publish.yml"] = PUBLISHER.replace("@WORKFLOWS@", "".join(f'      - "pkg: {p}"\n' for p in pkgs))
	return files


def main():
	files = generate()
	stale = [os.path.basename(f) for f in glob.glob(f"{WF}/pkg-*.yml") if os.path.basename(f) not in files]
	if "--check" in sys.argv[1:]:
		bad = [n for n, t in sorted(files.items())
		       if not os.path.exists(f"{WF}/{n}") or open(f"{WF}/{n}").read() != t] + stale
		for n in bad:
			print(f"!! .github/workflows/{n} isn't what github-ci/gen-workflows.py writes (run it)")
		print(f">> {len(files) - 2} package workflows, walnut-package.yml and walnut-publish.yml: {'%d stale' % len(bad) if bad else 'current'}")
		lint = workflow_lint()
		for e in lint:
			print(f"!! {e}")
		return 1 if bad or lint else 0
	for n, t in files.items():
		with open(f"{WF}/{n}", "w") as f:
			f.write(t)
	for n in stale:
		os.unlink(f"{WF}/{n}")
	print(f">> {len(files) - 2} package workflows, walnut-package.yml and walnut-publish.yml")
	return 0


if __name__ == "__main__":
	sys.exit(main())
