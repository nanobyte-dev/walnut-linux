#!/usr/bin/env python3
"""bin2c.py IMAGE NAME: a raw vseal image as a C header (run with python3 -I): NAME[] and NAME_sha256[]."""
import hashlib, sys
data = open(sys.argv[1], 'rb').read()
name = sys.argv[2]
d = hashlib.sha256(data).digest()
guard = 'PS3RSX_' + name.upper() + '_H'
print('/* SPDX-License-Identifier: GPL-2.0 */')
print('/* %s.h: GENERATED by spu/Makefile (make -C spu, the spu-elf toolchain) from spu/vseal.c and the' % name)
print(' * crypto files next to it: the raw image loaded at LS 0 and its SHA-256, which spe.c checks once at load.')
print(' * %d bytes, sha256 %s. Regenerate, never edit. */' % (len(data), d.hex()))
print('#ifndef %s\n#define %s' % (guard, guard))
print('static const unsigned char %s[%d] __aligned(16) = {' % (name, len(data)))
for i in range(0, len(data), 12):
    print('\t' + ' '.join('0x%02x,' % b for b in data[i:i + 12]))
print('};')
print('static const unsigned char %s_sha256[32] = {' % name)
for i in range(0, 32, 8):
    print('\t' + ' '.join('0x%02x,' % b for b in d[i:i + 8]))
print('};\n#endif')
