#!/usr/bin/env python3
"""bin2c.py IMAGE: the raw vseal image as ../src/vseal_spu.h (run with python3 -I)."""
import hashlib, sys
data = open(sys.argv[1], 'rb').read()
d = hashlib.sha256(data).digest()
print('/* SPDX-License-Identifier: GPL-2.0 */')
print('/* vseal_spu.h: GENERATED by spu/Makefile (make -C spu, the spu-elf toolchain) from spu/vseal.c and the')
print(' * crypto files next to it: the raw image loaded at LS 0 and its SHA-256, which spe.c checks once at load.')
print(' * %d bytes, sha256 %s. Regenerate, never edit. */' % (len(data), d.hex()))
print('#ifndef PS3RSX_VSEAL_SPU_H\n#define PS3RSX_VSEAL_SPU_H')
print('static const unsigned char vseal_spu[%d] __aligned(16) = {' % len(data))
for i in range(0, len(data), 12):
    print('\t' + ' '.join('0x%02x,' % b for b in data[i:i + 12]))
print('};')
print('static const unsigned char vseal_spu_sha256[32] = {')
for i in range(0, 32, 8):
    print('\t' + ' '.join('0x%02x,' % b for b in d[i:i + 8]))
print('};\n#endif')
