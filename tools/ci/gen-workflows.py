#!/usr/bin/env python3
"""gen-workflows.py: writes .github/workflows/pkg-<name>.yml for every package GitHub builds
(every directory with a package.conf except the licensed ones). Each runs the package's build and
testing publish when a push touches what its version counts (tools/deb-version.sh: the directory,
the shared packaging tools, package.conf VERSION_PATHS) or its own workflow, and the stable
release by hand. ps3rsx also runs after every linux build: it builds against the new kernel.
Stale pkg-*.yml files are removed. Run it after adding or removing a package."""
import glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WF = f"{ROOT}/.github/workflows"
SHARED = ["tools/deb-prepare.sh", "tools/deb-build.sh", "tools/deb-chroot.sh", "docker/Dockerfile.deb"]


def conf(pkg, key):
	m = re.search(rf'^{key}="?([^"\n]*)"?$', open(f"{ROOT}/{pkg}/package.conf").read(), re.M)
	return m.group(1).split() if m else []


def main():
	licensed = {l.strip() for l in open(f"{ROOT}/tools/licensed-packages.txt") if l.strip() and not l.startswith("#")}
	pkgs = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(f"{ROOT}/*/package.conf"))
	pkgs = [p for p in pkgs if p not in licensed]
	written = set()
	for pkg in pkgs:
		paths = [f"{pkg}/**"] + SHARED + [f"{v.rstrip('/')}/**" if os.path.isdir(f"{ROOT}/{v}") else v
		                                  for v in conf(pkg, "VERSION_PATHS")] + [f".github/workflows/pkg-{pkg}.yml"]
		extra = ""
		if pkg == "ps3rsx":
			extra = ('  workflow_run:\n    workflows: ["pkg: linux"]\n    types: [completed]\n    branches: [main]\n')
		cond = "\n    if: ${{ github.event_name != 'workflow_run' || github.event.workflow_run.conclusion == 'success' }}" if extra else ""
		text = f"""# Generated by tools/ci/gen-workflows.py: don't edit, run it again.
name: "pkg: {pkg}"

on:
  push:
    branches: [main]
    paths:
{''.join(f'      - "{p}"' + chr(10) for p in paths)}{extra}  workflow_dispatch:
    inputs:
      release:
        description: "Release testing's newest {pkg} to stable (no build)"
        type: boolean
        default: false

concurrency:
  group: pkg-{pkg}-${{{{ inputs.release == true && 'release' || 'build' }}}}
  cancel-in-progress: ${{{{ inputs.release != true }}}}

jobs:
  package:{cond}
    uses: ./.github/workflows/walnut-package.yml
    with:
      package: {pkg}
      release: ${{{{ inputs.release == true }}}}
    secrets: inherit
"""
		name = f"pkg-{pkg}.yml"
		with open(f"{WF}/{name}", "w") as f:
			f.write(text)
		written.add(name)
	for old in glob.glob(f"{WF}/pkg-*.yml"):
		if os.path.basename(old) not in written:
			os.unlink(old)
	print(f">> {len(written)} package workflows")


if __name__ == "__main__":
	main()
