#!/bin/bash
# Experiment for the SPU forward-port report (docs/SPU-GCC.md): transplants GCC 9.5's SPU backend
# into a current GCC release unchanged (only the GCC 13 .c -> .cc renames and the stabs header
# removal), builds the compiler with make -k, and collects the errors per file.
# Runs as the user in the SPU builder container. Env: SPU_GCC_VERSION, PORT_GCC_VERSION, JOBS.
# Output: build/spu-port/ (gcc-<new> tree, obj/, errors.txt, summary.txt)
set -uo pipefail
D=build/downloads
OUT=build/spu-port
OLD=build/spu-port-old-src
NEW=$OUT/gcc-$PORT_GCC_VERSION
if [ -e "$OUT" ]; then
	BK="build/old/$(date +%Y%m%d-%H%M%S)-spu-port"
	mkdir -p "$BK" && mv "$OUT" "$BK/"
fi
mkdir -p "$OUT" "$OLD"
[ -d "$OLD/gcc-$SPU_GCC_VERSION" ] || tar -xf "$D/gcc-$SPU_GCC_VERSION.tar.xz" -C "$OLD"
tar -xf "$D/gcc-$PORT_GCC_VERSION.tar.xz" -C "$OUT"
S="$OLD/gcc-$SPU_GCC_VERSION"

# The backend, unchanged except for file names
cp -r "$S/gcc/config/spu" "$NEW/gcc/config/"
cp -r "$S/gcc/common/config/spu" "$NEW/gcc/common/config/"
cp -r "$S/libgcc/config/spu" "$NEW/libgcc/config/"
for f in "$NEW/gcc/config/spu/spu.c" "$NEW/gcc/config/spu/spu-c.c" "$NEW/gcc/common/config/spu/spu-common.c"; do
	mv "$f" "${f%.c}.cc"
done
sed -i 's/spu-c\.c/spu-c.cc/g' "$NEW/gcc/config/spu/t-spu-elf"
# GCC 14 wants each .opt file's documentation URLs (generated from the HTML manual): none here
printf '; Autogenerated by regenerate-opt-urls.py from gcc/config/spu/spu.opt and generated HTML\n' \
	> "$NEW/gcc/config/spu/spu.opt.urls"

# config.gcc: the GCC 9 target stanza (without dbxelf.h: stabs went in GCC 13) and cpu_type
python3 - "$NEW/gcc/config.gcc" "$NEW/libgcc/config.host" <<'PY'
import sys
p = sys.argv[1]; s = open(p).read()
s = s.replace("tic6x-*-*)\n\tcpu_type=c6x", "spu*-*-*)\n\tcpu_type=spu\n\t;;\ntic6x-*-*)\n\tcpu_type=c6x", 1)
# the removal listed spu among the explicitly unsupported targets
assert " | spu*-*-*\t\t\t\t\\\n" in s
s = s.replace(" | spu*-*-*\t\t\t\t\\\n", "", 1)
stanza = '''spu-*-elf*)
	tm_file="elfos.h spu/spu-elf.h spu/spu.h newlib-stdint.h"
	tmake_file="spu/t-spu-elf"
	native_system_header_dir=/include
	extra_headers="spu_intrinsics.h spu_internals.h vmx2spu.h spu_mfcio.h vec_types.h spu_cache.h"
	extra_modes=spu/spu-modes.def
	c_target_objs="${c_target_objs} spu-c.o"
	cxx_target_objs="${cxx_target_objs} spu-c.o"
	;;
'''
i = s.index("tic6x-*-elf)\n")
s = s[:i] + stanza + s[i:]
open(p, "w").write(s)
p = sys.argv[2]; s = open(p).read()
s = s.replace("tic6x-*-*)\n\tcpu_type=c6x", "spu*-*-*)\n\tcpu_type=spu\n\t;;\ntic6x-*-*)\n\tcpu_type=c6x", 1)
i = s.index("tic6x-*-elf)\n")
s = s[:i] + 'spu-*-elf*)\n\ttmake_file="$tmake_file spu/t-elf t-libgcc-pic t-fdpbit"\n\t;;\n' + s[i:]
open(p, "w").write(s)
PY
grep -q "cpu_type=spu" "$NEW/gcc/config.gcc" || { echo "config.gcc: cpu_type not added"; exit 1; }

mkdir -p "$OUT/obj" && cd "$OUT/obj"
"$PWD/../gcc-$PORT_GCC_VERSION/configure" --target=spu-elf --prefix=/opt/spu-port \
	--enable-languages=c --with-newlib --without-headers --disable-nls --disable-shared \
	--disable-threads --disable-libssp --disable-werror > ../configure.log 2>&1 || {
	echo "configure failed"; tail -5 ../configure.log; exit 1; }
make -k -j"$JOBS" all-gcc > ../build.log 2>&1
echo "make all-gcc exit: $?" > ../summary.txt
cd ../../..
grep -E "^[^ ]*: (error|fatal error)" "$OUT/build.log" | sort -u > "$OUT/errors.txt"
{
	echo "errors (unique): $(wc -l < "$OUT/errors.txt")"
	echo "by file:"; sed 's/:.*//' "$OUT/errors.txt" | sed 's|.*/gcc/||' | sort | uniq -c | sort -rn
} >> "$OUT/summary.txt"
cat "$OUT/summary.txt"
